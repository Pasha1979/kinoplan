// ========== СЦЕНАРНЫЕ КОНСТАНТЫ ==========
// Неизменяемые значения, используемые при расчётах и рендеринге.

/** Количество символов ≈ на одну страницу формата A4.
 *  A4 = 210×297 мм, Courier 12pt, поля 2-3 см → ~1800 знаков на лист.
 */
export const CHARS_PER_PAGE = 1800

/** Минимальное количество страниц, которое может занимать сцена.
 *  Ноль страниц невозможен — любой заголовок + текст занимает хотя бы
 *  минимальный объём (0.1 стр ≈ 2 абзаца).
 */
export const MIN_SCENE_PAGES = 0.1

/** Базовая длительность экранного времени одной страницы, в секундах.
 *  Стандарт отрасли: 1 страница ≈ 55 секунд экранного времени.
 */
export const SECONDS_PER_PAGE = 55

/** Базовая длительность экранного времени одного символа, в секундах.
 *  Альтернативный расчёт: 1 символ ≈ 0.05 сек (≈ 20 символов/сек).
 */
export const SECONDS_PER_CHAR = 0.05

/** Длительность экранного времени одной строки диалога, в секундах.
 *  Средняя реплика персонажа ≈ 3 секунды экранного времени.
 *  Используется в комбинированном (гибком) методе хронометража.
 */
export const SECONDS_PER_DIALOG_LINE = 3

/** Высота листа A4, мм (стандарт ISO 216) */
export const A4_HEIGHT_MM = 297

/** Высота листа A4, мм (стандарт ISO 216) */
export const A4_WIDTH_MM = 210

/** Поля страницы сверху/снизу, мм (≈ 2 см). Вычитается из высоты A4
 *  для получения полезной высоты текста.
 */
export const PAGE_MARGIN_TOP_BOTTOM_MM = 20

/** Поля страницы слева/справа, мм (≈ 2-3 см).
 *  Левое поле чуть шире для скрепления.
 */
export const PAGE_MARGIN_LEFT_MM = 30
export const PAGE_MARGIN_RIGHT_MM = 20

/** Калибровочный коэффициент для виртуального PageCounter.
 *  Подгоняет рендеринг под реальный размер шрифта Word (0.77 ≈ 12pt Courier).
 */
export const WORD_RENDER_CALIBRATION = 0.77

/** Имитационная задержка API-запросов, мс (для dev-режима). */
export const API_MOCK_DELAY_MS = 100
