/**
 * Паттерн номера сцены для regex.
 * Классика: 1, 12, 1-9 (сериал-сцена).
 * Расширенная нумерация: 1-9-А, 1-9-G, 1-9 (бывш), 1.a — буквы, литеры и пометки в скобках.
 */
/**
 * Грязная реальность: «1-2 4 -1» (пробелы), «1-14 + 1-15» (комбинированный),
 * «14-42-БОБ», «1.a» — сегмент через -/+ любые букво-цифры, либо пробел+цифры.
 */
export const SCENE_NUMBER = '[0-9]+(?:\\s*[-+]\\s*[0-9A-Za-zА-Яа-яЁё]+|\\s+[0-9]+)*(?:\\.[A-Za-zА-Яа-яЁё]+)?(?:\\s*\\([^)]*\\))?'
